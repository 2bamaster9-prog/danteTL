"""The desktop's application port: commands and read-only snapshots only."""

from pathlib import Path
from typing import Protocol

from jp_overlay.application_notice import Notices
from jp_overlay.application_values import (
    ApplicationControls,
    ApplicationView,
    ModelConsent,
    ShutdownSnapshot,
)
from jp_overlay.domain import WindowTarget
from jp_overlay.history_values import HistoryTurn
from jp_overlay.model_selection import AssignmentChange, OcrOption
from jp_overlay.preference_values import Preferences
from jp_overlay.view_services import CloudCommands, SetupCommands


class ApplicationCommands(Protocol):
    @property
    def cloud(self) -> CloudCommands: ...
    @property
    def setup(self) -> SetupCommands: ...
    @property
    def values(self) -> Preferences: ...
    @property
    def view(self) -> ApplicationView: ...
    @property
    def controls(self) -> ApplicationControls: ...
    @property
    def ocr_options(self) -> tuple[OcrOption, ...]: ...
    @property
    def original(self) -> bool: ...
    @property
    def closing(self) -> bool: ...
    @property
    def close_status(self) -> ShutdownSnapshot: ...
    @property
    def can_setup(self) -> bool: ...
    @property
    def error(self) -> str: ...
    @property
    def error_revision(self) -> int: ...
    @property
    def history_turns(self) -> tuple[HistoryTurn, ...]: ...
    @property
    def history_status(self) -> str: ...
    def configure(self, values: Preferences) -> None: ...
    def assign(self, change: AssignmentChange) -> ModelConsent | None: ...
    def consent(self, token: int, accepted: bool) -> None: ...
    def set_window_title(self, title: str) -> None: ...
    def refresh_models(self) -> None: ...
    def clear_history(self) -> None: ...
    def clear_english(self) -> None: ...
    def take_destination(self) -> str: ...
    def offer_first_run(self) -> None: ...
    def setup_skipped(self) -> None: ...
    def setup_completed(self, model: str, target: Path | None) -> None: ...
    def request_close(self, target: Path | None = None) -> None: ...
    def show_original(self, held: bool, *, modal: bool = False) -> bool: ...
    def foreground_target(self) -> WindowTarget | None: ...
    def start_capture(self, target: WindowTarget, now: float) -> bool: ...
    def stop(self, message: str = "Capture stopped.") -> None: ...
    def set_diagnostics(self, *, boxes: bool, debug: bool) -> None: ...
    def notices(self) -> Notices: ...
    def advance(self, now: float) -> ApplicationView: ...
